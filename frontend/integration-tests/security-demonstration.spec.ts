import { test, expect } from '@playwright/test'

test('D P0: template provenance, real query, audit filters and denied project access', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '进入演示' }).click()
  await page.locator('.project-card').filter({ hasText: 'D contract A' }).getByRole('button', { name: '进入工作台' }).click()
  await page.getByRole('link', { name: '查询与审计', exact: true }).click()
  const projectId = new URL(page.url()).pathname.split('/')[2]!
  const target = page.url()
  await expect(page.getByTestId('scope-role')).toHaveText('负责人')
  await expect(page.getByText('开发演示身份', { exact: true })).toBeVisible()
  await expect(page.getByText(/当前使用三类固定模板降级/)).toBeVisible()
  await expect(page.getByText('可查询、管理成员、移出论文和查看审计', { exact: true })).toBeVisible()
  const executed = page.waitForResponse(r => r.request().method() === 'POST' && r.url().endsWith('/secure-queries'))
  await page.getByRole('button', { name: '提交查询', exact: true }).click()
  const result = await (await executed).json()
  expect(result).toMatchObject({ decision: 'allowed', execution_status: 'executed', mock: false })
  expect(result.policy_id).toMatch(/-template$/)
  await page.getByRole('button', { name: '不支持的问题', exact: true }).click()
  await page.getByRole('button', { name: '提交查询', exact: true }).click()
  await expect(page.getByRole('region', { name: '查询结果' }).getByText('rejected / not_executed', { exact: true })).toBeVisible()
  await page.getByLabel('审计事件类型').fill('security.query.finished')
  await page.getByLabel('审计起始时间').fill('2020-01-01T00:00:00Z')
  await page.getByLabel('审计结束时间').fill('2099-01-01T00:00:00Z')
  const me = await (await page.request.get('/api/v1/auth/me')).json()
  await page.getByLabel('审计用户').fill(me.user.user_id)
  await page.getByRole('combobox', { name: '审计决策', exact: true }).press('ArrowDown')
  await page.getByRole('option', { name: '拒绝 · rejected', exact: true }).click()
  const filtered = page.waitForResponse(r => r.request().method() === 'GET' && r.url().includes('/audit-events?') && r.url().includes('decision=rejected'))
  await page.getByRole('button', { name: '筛选审计', exact: true }).click()
  const audit = await (await filtered).json()
  expect(audit.items.length).toBeGreaterThan(0)
  expect(audit.items.every((event: { decision: string; project_id: string; actor_id: string }) => event.decision === 'rejected' && event.project_id === projectId && event.actor_id === me.user.user_id)).toBe(true)
  expect((await page.request.post(`/api/v1/projects/${projectId}/members`, { headers: { 'X-PaperPilot-Client': 'web' }, data: { username: 'bob' } })).status()).toBe(201)
  await page.getByRole('button', { name: '退出', exact: true }).click()
  await expect(page.getByRole('heading', { name: '开发演示登录' })).toBeVisible()
  await page.getByRole('combobox', { name: '演示身份', exact: true }).press('ArrowDown')
  await page.getByRole('option', { name: 'bob', exact: true }).click()
  await page.getByRole('button', { name: '进入演示' }).click()
  await expect(page.getByRole('heading', { name: '你的研究项目' })).toBeVisible()
  await page.goto(target)
  await expect(page.getByTestId('scope-role')).toHaveText('成员')
  await expect(page.getByText('可参与文献研究与查询；成员管理、移出论文和完整审计仅负责人可用', { exact: true })).toBeVisible()
  expect((await page.request.get(`/api/v1/projects/${projectId}/audit-events`)).status()).toBe(403)
  await page.getByRole('button', { name: '退出', exact: true }).click()
  await expect(page.getByRole('heading', { name: '开发演示登录' })).toBeVisible()
  await page.getByRole('combobox', { name: '演示身份', exact: true }).press('ArrowDown')
  await page.getByRole('option', { name: 'eve', exact: true }).click()
  await page.getByRole('button', { name: '进入演示' }).click()
  await expect(page.getByRole('heading', { name: '你的研究项目' })).toBeVisible()
  await page.goto(target)
  await expect(page.getByTestId('scope-role')).toHaveText('待确认')
  await expect(page.getByRole('alert').filter({ hasText: 'RESOURCE_NOT_FOUND' })).toBeVisible()
  const denied = await page.request.post(`/api/v1/projects/${projectId}/secure-queries`, { headers: { 'X-PaperPilot-Client': 'web' }, data: { question: '按年份统计论文数量' } })
  expect(denied.status()).toBe(404)
  expect(await denied.text()).not.toContain('rows')
})
