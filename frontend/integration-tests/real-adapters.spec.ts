import { test, expect } from '@playwright/test'

test('disposable PostgreSQL + real C/D: PDF sources, generation, versions, SQL decisions and audit', async ({ page }) => {
  const reportTitle = `真实适配器联调-${Date.now()}`
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await page.getByRole('button', { name: '进入演示' }).click()
  await expect(page.getByRole('heading', { name: '你的研究项目' })).toBeVisible()
  await expect(page.getByRole('button', { name: '查看运行说明' })).toBeVisible()
  await page.locator('.project-card').filter({ hasText: 'D contract A' }).getByRole('button', { name: '进入工作台' }).click()
  await expect(page.locator('.paper-status.paper-state-searchable')).toBeVisible()
  await page.getByRole('link', { name: '研究', exact: true }).click()
  await expect(page.getByTestId('active-source')).toContainText('PaperPilot RAG integration')
  await page.getByLabel('研究问题', { exact: true }).fill('RAG integration')
  await page.getByRole('tab', { name: '检索结果', exact: true }).click()
  const searched = page.waitForResponse(response => response.request().method() === 'POST' && response.url().endsWith('/search'))
  await page.getByRole('button', { name: '检索', exact: true }).click()
  expect((await (await searched).json()).items.length).toBeGreaterThan(0)
  await page.getByRole('tab', { name: '来源片段', exact: true }).click()
  await expect(page.getByTestId('active-source')).toContainText('PaperPilot RAG integration')
  await page.getByRole('tab', { name: '证据', exact: true }).click()
  await page.getByRole('button', { name: '提取证据', exact: true }).click()
  await expect(page.getByText('AI 提取 · 待核验', { exact: true })).toBeVisible()
  await page.getByRole('tab', { name: '问答', exact: true }).click()
  await page.getByRole('button', { name: '生成回答', exact: true }).click()
  await expect(page.getByText('AI 回答 · 待核验', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '查看引用 [1]', exact: true }).click()
  await expect(page.getByTestId('active-source')).toContainText('PaperPilot RAG integration')
  await page.getByRole('tab', { name: '报告', exact: true }).click()
  await page.getByLabel('报告研究问题').fill('RAG integration')
  await page.getByRole('button', { name: '生成草稿', exact: true }).click()
  await expect(page.getByLabel('报告正文')).toHaveValue(/文献研究草稿/)
  await page.getByLabel('报告标题').fill(reportTitle)
  await page.getByRole('button', { name: '保存新版本' }).click()
  await expect(page.getByRole('button', { name: '版本 1', exact: true })).toBeVisible()
  await page.screenshot({ path: '../.runtime/browser-research.png', fullPage: true })
  await page.reload()
  await page.getByRole('tab', { name: '报告', exact: true }).click()
  await page.getByRole('button', { name: `${reportTitle} · v1` }).click()
  const discard = page.getByRole('button', { name: '放弃未保存编辑并继续' })
  if (await discard.isVisible()) await discard.click()
  await expect(page.getByRole('button', { name: '版本 1', exact: true })).toBeVisible()
  await expect(page.getByLabel('报告正文')).toHaveValue(/文献研究草稿/)
  await page.getByRole('link', { name: '查询与审计', exact: true }).click()
  const evidence = page.getByRole('region', { name: '安全验证证据' })
  await expect(evidence).toContainText('隔离 PostgreSQL 测试通过')
  await expect(evidence).toContainText('生产认证与正式业务库部署未验收')
  await page.getByLabel('统计问题').fill('按年份统计论文数量')
  await page.getByRole('button', { name: '提交查询', exact: true }).click()
  await expect(page.getByText('allowed / executed', { exact: true })).toBeVisible()
  await page.getByLabel('审计事件类型').fill('security.query.finished')
  await page.getByRole('button', { name: '筛选审计' }).click()
  await expect(page.locator('.audit-table')).toContainText('security.query.finished')
  await page.getByLabel('统计问题').fill('SELECT * FROM users')
  await page.getByRole('button', { name: '提交查询', exact: true }).click()
  await expect(page.getByText('rejected / not_executed', { exact: true })).toBeVisible()
  await page.screenshot({ path: '../.runtime/browser-security.png', fullPage: true })
  expect(errors).toEqual([])
})
