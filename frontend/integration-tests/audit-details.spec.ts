import { test, expect } from '@playwright/test'

test('real PostgreSQL audit exposes persisted questions and validated parameterized SQL', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '进入演示' }).click()
  await page.locator('.project-card').filter({ hasText: 'D contract A' }).getByRole('button', { name: '进入工作台' }).click()
  await page.getByRole('link', { name: '查询与审计', exact: true }).click()
  await page.getByRole('button', { name: '提交查询', exact: true }).click()
  await expect(page.getByText('allowed / executed', { exact: true })).toBeVisible()
  await page.reload()
  await page.getByLabel('审计事件类型').fill('secure_query.finished')
  await page.getByRole('button', { name: '筛选审计', exact: true }).click()
  await page.getByRole('button', { name: '查看详情', exact: true }).first().click()
  const dialog = page.getByRole('dialog', { name: '审计操作详情' })
  await expect(dialog).toContainText('按年份统计论文数量')
  await dialog.getByRole('button', { name: 'Close this dialog' }).click()
  await page.getByLabel('审计事件类型').fill('security.query.finished')
  await page.getByRole('button', { name: '筛选审计', exact: true }).click()
  await page.getByRole('button', { name: '查看详情', exact: true }).first().click()
  await expect(dialog.getByRole('heading', { name: '已校验的参数化 SQL' })).toBeVisible()
  await expect(dialog.locator('pre')).toContainText('%(project_id)s')
  await expect(dialog.locator('pre')).toContainText('LIMIT 100')
  await expect(dialog).toContainText('按年份统计论文数量')
  await expect(dialog).toContainText('记录了 SQL 不代表执行成功')
  await dialog.getByRole('button', { name: 'Close this dialog' }).click()
  await page.getByRole('button', { name: '不支持的问题', exact: true }).click()
  await page.getByRole('button', { name: '提交查询', exact: true }).click()
  await expect(page.getByText('rejected / not_executed', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '查看详情', exact: true }).first().click()
  await expect(dialog.locator('pre')).toHaveCount(0)
  await expect(dialog).toContainText('不支持的问题')
})
