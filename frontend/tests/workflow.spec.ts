test('upload retry keeps the request key after an unknown commit result', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '进入演示' }).click()
  await page.getByLabel('新项目名称').fill('上传对账测试')
  await page.getByRole('button', { name: '创建项目' }).click()
  await page.getByLabel('选择 PDF 文件').setInputFiles({ name: 'retry.pdf', mimeType: 'application/pdf', buffer: Buffer.from('%PDF-1.4\nRetry fixture') })
  const keys: string[] = []
  await page.route('**/api/v1/projects/*/papers', async route => {
    if (route.request().method() !== 'POST') return route.continue()
    keys.push(route.request().headers()['idempotency-key'] || '')
    const response = await route.fetch()
    if (keys.length === 1) {
      await route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ code: 'DATA_COMMIT_UNKNOWN', message: '提交状态待确认，请重试', request_id: '00000000-0000-4000-8000-000000000001' }) })
    } else await route.fulfill({ response })
  })
  await page.getByRole('button', { name: '上传并模拟处理' }).click()
  await expect(page.getByRole('region', { name: '任务恢复' }).getByText(/提交结果未知/)).toBeVisible()
  await page.getByRole('button', { name: '使用原请求核对' }).click()
  await expect(page.getByText('任务：succeeded')).toBeVisible()
  expect(keys).toHaveLength(2)
  expect(keys[0]).toBeTruthy()
  expect(keys[1]).toBe(keys[0])
})

test('report retry reuses its key and reads the same saved version', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '进入演示' }).click()
  await page.getByLabel('新项目名称').fill('报告对账测试')
  await page.getByRole('button', { name: '创建项目' }).click()
  await page.getByRole('link', { name: '研究', exact: true }).click()
  await page.getByLabel('报告正文').fill('不明提交后重新读取的报告')
  const keys: string[] = []
  await page.route('**/api/v1/projects/*/reports', async route => {
    if (route.request().method() !== 'POST') return route.continue()
    keys.push(route.request().headers()['idempotency-key'] || '')
    const response = await route.fetch()
    if (keys.length === 1) await route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ code: 'DATA_COMMIT_UNKNOWN', message: '提交状态待确认，请重试', request_id: '00000000-0000-4000-8000-000000000001' }) })
    else await route.fulfill({ response })
  })
  await page.getByRole('button', { name: '保存新版本' }).click()
  await expect(page.getByRole('alert').filter({ hasText: 'DATA_COMMIT_UNKNOWN' })).toBeVisible()
  await page.getByRole('button', { name: '保存新版本' }).click()
  await expect(page.getByRole('button', { name: '版本 1', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: '版本 2', exact: true })).toHaveCount(0)
  expect(keys).toHaveLength(2)
  expect(keys[0]).toBeTruthy()
  expect(keys[1]).toBe(keys[0])
})
