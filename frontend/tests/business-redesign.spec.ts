import { test, expect, type Page } from '@playwright/test'

async function createProject(page: Page) {
  await page.goto('/')
  await page.getByRole('button', { name: '进入演示' }).click()
  await page.getByLabel('新项目名称').fill(`页面改版-${Date.now()}`)
  await page.getByRole('button', { name: '创建项目' }).click()
  await expect(page.getByRole('heading', { name: '文献工作台' })).toBeVisible()
}

async function fits(page: Page) {
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
}

for (const width of [304, 390, 768, 1440]) {
  test(`redesigned workspaces at ${width}px preserve sources, evidence, versions and audit`, async ({ page }) => {
    await page.setViewportSize({ width, height: 1000 })
    const errors: string[] = []
    page.on('pageerror', error => errors.push(error.message))
    await createProject(page)
    // The initial anonymous session probe legitimately returns 401; authenticated operations must be clean.
    page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
    await expect(page.getByText('当前范围内没有文献')).toBeVisible()
    const upload = page.getByLabel('选择 PDF 文件')
    await upload.focus()
    await expect(upload).toBeFocused()
    await upload.setInputFiles({ name: 'research-preview.pdf', mimeType: 'application/pdf', buffer: Buffer.from(`%PDF-1.4\nMock preview ${width}`) })
    await expect(page.locator('.selected-file')).toContainText('research-preview.pdf')
    await page.getByLabel('论文标题', { exact: true }).fill('检索增强生成：科研文献中的来源核验与证据追溯')
    await page.getByRole('button', { name: '上传并模拟处理' }).click()
    await expect(page.getByText('任务：succeeded')).toBeVisible()
    await expect(page.locator('.document-table')).toContainText('检索增强生成：科研文献中的来源核验与证据追溯')
    await fits(page)
    await page.screenshot({ path: `../output/business-redesign/${width}-papers.png`, fullPage: true, animations: 'disabled' })
    await page.getByRole('button', { name: '详情', exact: true }).click()
    await page.getByText('[1] 第 1 页 · 合成来源，待核验', { exact: true }).click()
    await expect(page.locator('.source-excerpt p')).toContainText('不是从 PDF 提取的原文')
    await fits(page)
    await page.screenshot({ path: `../output/business-redesign/${width}-source.png`, animations: 'disabled' })
    await page.getByRole('button', { name: 'Close this dialog' }).click()
    await page.getByRole('link', { name: '研究', exact: true }).click()
    await page.getByRole('button', { name: '检索', exact: true }).click()
    await expect(page.getByText('1 条结果', { exact: true })).toBeVisible()
    await page.getByRole('button', { name: '提取 Mock 证据' }).click()
    const evidence = page.locator('.evidence-fields')
    const limitations = evidence.getByRole('button', { name: /研究局限/ })
    await expect(limitations).toHaveAttribute('aria-expanded', 'false')
    await limitations.click()
    await expect(limitations).toHaveAttribute('aria-expanded', 'true')
    await expect(evidence.getByText('未提及或证据不足')).toBeVisible()
    await evidence.getByRole('button', { name: '支撑来源' }).first().click()
    await expect(page.getByRole('dialog', { name: '引用来源 · 合成数据' })).toBeVisible()
    await page.getByRole('button', { name: 'Close this dialog' }).click()
    await page.getByRole('button', { name: '生成 Mock 回答' }).click()
    await expect(page.locator('.answer-prose')).toContainText('不代表真实研究结论')
    await page.getByRole('button', { name: '生成 Mock 草稿' }).click()
    await expect(page.getByLabel('报告正文')).toHaveValue(/Mock 合成内容/)
    await page.getByRole('button', { name: '保存新版本' }).click()
    await expect(page.getByRole('button', { name: '版本 1', exact: true })).toBeVisible()
    await fits(page)
    await page.screenshot({ path: `../output/business-redesign/${width}-research.png`, fullPage: true, animations: 'disabled' })
    await page.getByRole('link', { name: '查询与审计', exact: true }).click()
    await page.getByRole('button', { name: '提交 Mock 查询' }).click()
    await expect(page.getByText('演示结果已返回，未执行真实 SQL', { exact: true })).toBeVisible()
    await expect(page.locator('.audit-table')).toContainText('secure_query.finished')
    await fits(page)
    await page.screenshot({ path: `../output/business-redesign/${width}-security.png`, fullPage: true, animations: 'disabled' })
    expect(errors).toEqual([])
  })
}

test('query result keeps submitted question and disclosed error examples retain original behavior', async ({ page }) => {
  await createProject(page)
  await page.getByRole('link', { name: '查询与审计', exact: true }).click()
  await page.getByRole('button', { name: '提交 Mock 查询' }).click()
  await expect(page.getByText('allowed / executed', { exact: true })).toBeVisible()
  await page.getByLabel('统计问题').fill('尚未提交的新问题')
  await expect(page.locator('.query-result-summary')).toContainText('按年份统计论文数量')
  await expect(page.locator('.query-result-summary')).not.toContainText('尚未提交的新问题')
  await page.getByText('异常场景演示', { exact: true }).click()
  await page.getByRole('button', { name: '模拟执行失败', exact: true }).click()
  await expect(page.getByLabel('统计问题')).toHaveValue('模拟执行失败')
  await page.getByRole('button', { name: '提交 Mock 查询' }).click()
  await expect(page.getByText('查询执行失败，没有可用结果', { exact: true })).toBeVisible()
  await expect(page.locator('.query-result-table')).toHaveCount(0)
  await page.getByRole('button', { name: '清除查询结果' }).click()
  await expect(page.getByText('输入统计问题后提交查询')).toBeVisible()
})
